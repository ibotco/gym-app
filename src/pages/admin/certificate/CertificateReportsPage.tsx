import { useMemo, useState } from 'react'
import { BarChart3, FileText, Pencil, Plus, Printer, ShieldAlert, Trash2 } from 'lucide-react'
import { Badge, Button, Field, Input, Modal, PageHeader, SearchInput, Select } from '../../../components/ui'
import { DataTable, type Column } from '../../../components/DataTable'
import { useToast } from '../../../context/ToastContext'
import { useCertificateContext } from './CertificateShared'
import { uid } from '../../../lib/utils'
import type { EduRow } from '../../../lib/eduRecords'

const REPORT_TYPES = ['Issued', 'Pending', 'Revoked', 'Verification', 'Summary'] as const

type Draft = { title: string; fromDate: string; toDate: string; holderType: string; certificateType: string; reportType: string; generatedBy: string }

export function CertificateReportsPage() {
  const { reports, generations, verifications, types, can, patch } = useCertificateContext()
  const toast = useToast()
  const allowed = can('reports')
  const [query, setQuery] = useState('')
  const [editing, setEditing] = useState<EduRow | null>(null)
  const [draft, setDraft] = useState<Draft>({ title: '', fromDate: '', toDate: '', holderType: 'All', certificateType: '', reportType: 'Summary', generatedBy: '' })
  const [confirmDelete, setConfirmDelete] = useState<EduRow | null>(null)

  const typeNames = useMemo(() => types.map((r) => String(r.name ?? '')).filter(Boolean), [types])

  const stats = useMemo(() => ({
    issued: generations.filter((r) => String(r.status ?? '').toLowerCase() === 'issued').length,
    draft: generations.filter((r) => String(r.status ?? '').toLowerCase() === 'draft').length,
    revoked: generations.filter((r) => String(r.status ?? '').toLowerCase() === 'revoked').length,
    verified: verifications.length,
  }), [generations, verifications])

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase()
    if (!q) return reports
    return reports.filter((r) => [r.title, r.reportType, r.certificateType, r.generatedBy].some((v) => String(v ?? '').toLowerCase().includes(q)))
  }, [reports, query])

  const openNew = () => { setDraft({ title: '', fromDate: '', toDate: '', holderType: 'All', certificateType: '', reportType: 'Summary', generatedBy: '' }); setEditing({ id: '' } as EduRow) }
  const openEdit = (row: EduRow) => {
    setDraft({
      title: String(row.title ?? ''),
      fromDate: String(row.fromDate ?? ''),
      toDate: String(row.toDate ?? ''),
      holderType: String(row.holderType ?? 'All'),
      certificateType: String(row.certificateType ?? ''),
      reportType: String(row.reportType ?? 'Summary'),
      generatedBy: String(row.generatedBy ?? ''),
    })
    setEditing(row)
  }
  const save = () => {
    if (!draft.title.trim()) { toast.error('Title required', 'Give the report a title.'); return }
    const row: EduRow = {
      id: editing?.id || uid('certrep'),
      title: draft.title.trim(),
      fromDate: draft.fromDate,
      toDate: draft.toDate,
      holderType: draft.holderType,
      certificateType: draft.certificateType,
      reportType: draft.reportType,
      generatedBy: draft.generatedBy.trim() || 'System',
      createdAt: new Date().toISOString(),
    }
    const next = editing?.id ? reports.map((r) => r.id === editing.id ? row : r) : [...reports, row]
    patch({ certificateReports: next as EduRow[] })
    toast.success(editing?.id ? 'Report updated' : 'Report created', draft.title)
    setEditing(null)
  }
  const remove = () => {
    if (!confirmDelete) return
    patch({ certificateReports: reports.filter((r) => r.id !== confirmDelete.id) as EduRow[] })
    toast.success('Deleted', String(confirmDelete.title ?? 'Report'))
    setConfirmDelete(null)
  }

  const columns: Column<EduRow>[] = [
    { key: 'title', header: 'Report Title', render: (r) => <div><p className="font-semibold">{String(r.title ?? '')}</p><p className="text-[11px] text-mist">{String(r.reportType ?? '')} · {String(r.certificateType ?? 'All types')}</p></div> },
    { key: 'fromDate', header: 'Period', render: (r) => <span className="text-sm">{String(r.fromDate ?? '—')} — {String(r.toDate ?? '—')}</span> },
    { key: 'generatedBy', header: 'Generated By', render: (r) => <span className="text-sm">{String(r.generatedBy ?? '—')}</span> },
    { key: 'reportType', header: 'Type', render: (r) => <Badge tone="zinc">{String(r.reportType ?? '')}</Badge> },
    {
      key: 'actions', header: '', width: 120, render: (r) => (
        <div className="flex justify-end gap-1">
          <Button size="sm" variant="outline" onClick={() => window.print()}><Printer className="size-3.5" /></Button>
          <Button size="sm" variant="outline" disabled={!allowed} onClick={() => openEdit(r)}><Pencil className="size-3.5" /></Button>
          <Button size="sm" variant="outline" disabled={!allowed} onClick={() => setConfirmDelete(r)}><Trash2 className="size-3.5 text-rose" /></Button>
        </div>
      ),
    },
  ]

  return (
    <div className="space-y-5">
      <PageHeader eyebrow="Certificate Management" title="Certificate Reports" desc="Generate and review issuance, verification and summary reports for auditing." printTitle="Certificate Reports" />
      {!allowed && <p className="flex items-center gap-2 rounded-xl border border-amber-400/40 bg-amber-400/10 px-3 py-2 text-sm text-amber-700 dark:text-amber-300"><ShieldAlert className="size-4" /> Your role cannot manage reports.</p>}

      <div className="grid gap-3 sm:grid-cols-4">
        <div className="rounded-2xl border border-line bg-white p-4 dark:bg-white/5"><p className="text-[11px] font-bold uppercase tracking-widest text-mist">Issued</p><p className="mt-1 text-2xl font-extrabold">{stats.issued}</p></div>
        <div className="rounded-2xl border border-line bg-white p-4 dark:bg-white/5"><p className="text-[11px] font-bold uppercase tracking-widest text-mist">Pending / Draft</p><p className="mt-1 text-2xl font-extrabold">{stats.draft}</p></div>
        <div className="rounded-2xl border border-line bg-white p-4 dark:bg-white/5"><p className="text-[11px] font-bold uppercase tracking-widest text-mist">Revoked</p><p className="mt-1 text-2xl font-extrabold">{stats.revoked}</p></div>
        <div className="rounded-2xl border border-line bg-white p-4 dark:bg-white/5"><p className="text-[11px] font-bold uppercase tracking-widest text-mist">Verifications</p><p className="mt-1 text-2xl font-extrabold">{stats.verified}</p></div>
      </div>

      <div className="flex flex-wrap items-center gap-3">
        <SearchInput value={query} onChange={setQuery} placeholder="Search reports…" className="max-w-xs" />
        <div className="ml-auto flex gap-2">
          <Badge tone="zinc">{filtered.length} report{filtered.length === 1 ? '' : 's'}</Badge>
          <Button size="sm" onClick={openNew} disabled={!allowed}><Plus className="size-4" /> New Report</Button>
        </div>
      </div>
      <DataTable<EduRow> data={filtered as EduRow[]} columns={columns} rowKey={(r) => String(r.id)} emptyTitle="No reports yet" emptyDesc="Create a report to summarise certificate activity." />

      <Modal open={!!editing} onClose={() => setEditing(null)} title={editing?.id ? 'Edit Report' : 'New Report'} footer={<><Button variant="outline" size="sm" onClick={() => setEditing(null)}>Cancel</Button><Button size="sm" onClick={save} disabled={!allowed}>Save</Button></>}>
        <div className="grid gap-4">
          <Field label="Report Title *"><Input value={draft.title} onChange={(e) => setDraft({ ...draft, title: e.target.value })} placeholder="e.g. Monthly Issuance — June 2026" /></Field>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field label="From Date"><Input type="date" value={draft.fromDate} onChange={(e) => setDraft({ ...draft, fromDate: e.target.value })} /></Field>
            <Field label="To Date"><Input type="date" value={draft.toDate} onChange={(e) => setDraft({ ...draft, toDate: e.target.value })} /></Field>
          </div>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field label="Holder Type"><Select value={draft.holderType} onChange={(e) => setDraft({ ...draft, holderType: e.target.value })}><option>All</option><option>Student</option><option>Employee</option><option>Member</option></Select></Field>
            <Field label="Certificate Type"><Select value={draft.certificateType} onChange={(e) => setDraft({ ...draft, certificateType: e.target.value })}><option value="">All types</option>{typeNames.map((n) => <option key={n} value={n}>{n}</option>)}</Select></Field>
          </div>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field label="Report Type"><Select value={draft.reportType} onChange={(e) => setDraft({ ...draft, reportType: e.target.value })}>{REPORT_TYPES.map((o) => <option key={o} value={o}>{o}</option>)}</Select></Field>
            <Field label="Generated By"><Input value={draft.generatedBy} onChange={(e) => setDraft({ ...draft, generatedBy: e.target.value })} placeholder="e.g. Admin" /></Field>
          </div>
        </div>
      </Modal>

      <Modal open={!!confirmDelete} onClose={() => setConfirmDelete(null)} title="Delete report?" footer={<><Button variant="outline" size="sm" onClick={() => setConfirmDelete(null)}>Cancel</Button><Button size="sm" tone="danger" onClick={remove}>Delete</Button></>}>
        <p className="text-sm">Delete <b>{String(confirmDelete?.title ?? '')}</b>? This cannot be undone.</p>
      </Modal>
    </div>
  )
}
